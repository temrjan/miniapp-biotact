def upgrade() -> None:
    """EXPAND phase of the ticket-as-a-record model. Additive and relaxing only.

    Nothing here is removed or tightened without a default, because the code running in production
    the moment this lands is still the PREVIOUS logic: ``period`` is what it identifies draws by,
    ``ORDER BY period DESC`` is how the member's card finds the latest one, and ``commit_draw`` still
    creates a draw that is born frozen. Dropping ``period`` in the same step would answer that code
    with ``UndefinedColumn`` on every card open — the shape of incident #30. The removals
    (``period``, the dead ``open`` state) belong to the CONTRACT phase, after steps 2-5 have moved
    every read onto ``draw_number``.

    * ``lottery_draws.draw_number`` — the identity that replaces the calendar month. ``GENERATED BY
      DEFAULT AS IDENTITY``, therefore NOT NULL is safe here: an INSERT that never heard of the
      column still gets a number, so the pre-step-3 ``commit_draw`` keeps working untouched and no
      ``draw_number IS NULL`` row can ever exist for the contract phase to trip over. The number
      comes from the identity sequence rather than ``MAX + 1`` — two concurrent freezes would read
      the same maximum.
      ⚠️ The identity default is VOLATILE, so PostgreSQL rewrites the table to fill existing rows.
      That is instant here and only here: both lottery tables are verified empty on production
      (release checklist runs the count immediately before merge, and a non-zero answer stops this
      migration).
    * ``conducted_on`` — the announced date of the draw. ``DATE``, not a timestamp: it is shown to
      people and never computed against. Nullable, and deliberately outside the published hash, so a
      postponed draw cannot break a fingerprint already published.
    * ``cancelled_at`` / ``cancelled_snapshot`` — the audit trail of a cancelled draw. The snapshot
      holds the canonical TEXT, the exact bytes the published SHA-256 was taken over, so the trail
      can be re-hashed and checked against ``participant_hash`` in the same row.
    * ``lottery_tickets.draw_id`` / ``ticket_number`` — relaxed to NULL. A ticket becomes a record
      owned by a member; a freeze is what stamps it into a draw. Relaxing is backward compatible:
      today's writer always supplies both. ``UNIQUE(draw_id, ticket_number)`` is untouched and stays
      correct — PostgreSQL treats NULLs as distinct, so clean ``(NULL, NULL)`` rows never collide.
    * ``backfill_batch`` — marker for the one-off backfill of step 2. It ships here, in the same
      migration as the columns it annotates: without it the promised rollback of the backfill has
      nothing to select on, and adding it later would cost a second schema PR.
    * ``ix_lottery_tickets_clean_user`` — PARTIAL index on the only hot query of the new model
      (a member's clean tickets: the ceiling of two, and the freeze that stamps them).
    """
    op.add_column(
        "lottery_draws",
        sa.Column("draw_number", sa.Integer(), sa.Identity(always=False), nullable=False),
    )
    op.create_unique_constraint(
        "lottery_draws_draw_number_key", "lottery_draws", ["draw_number"]
    )
    op.add_column("lottery_draws", sa.Column("conducted_on", sa.Date(), nullable=True))
    op.add_column(
        "lottery_draws", sa.Column("cancelled_at", sa.DateTime(timezone=True), nullable=True)
    )
    op.add_column("lottery_draws", sa.Column("cancelled_snapshot", sa.Text(), nullable=True))

    op.alter_column(
        "lottery_tickets", "draw_id", existing_type=sa.Integer(), nullable=True
    )
    op.alter_column(
        "lottery_tickets", "ticket_number", existing_type=sa.Integer(), nullable=True
    )
    op.add_column(
        "lottery_tickets", sa.Column("backfill_batch", sa.String(length=32), nullable=True)
    )
    op.create_index(
        "ix_lottery_tickets_clean_user",
        "lottery_tickets",
        ["user_id"],
        unique=False,
        postgresql_where=sa.text("draw_id IS NULL"),
    )


